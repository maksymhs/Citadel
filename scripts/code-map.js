#!/usr/bin/env node
/**
 * Regenerates docs/code-map.md: one line per source file, taken from the file's
 * own header comment, plus an index of the screens in public/js/app.js.
 * Run `node scripts/code-map.js` after adding, moving or re-purposing a file.
 * To improve a description, edit the header comment of the file, not the map.
 */
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');
const GROUPS = [
  ['HTTP routes', 'server/routes', /\.js$/],
  ['Services', 'server/services', /\.js$/],
  ['Security', 'server/security', /\.js$/],
  ['Core', 'server', /^(index|config)\.js$/],
  ['Core', 'server/database', /\.js$/],
  ['Core', 'server/modules', /\.js$/],
  ['CLI and scripts', 'scripts', /\.(js|sh)$/],
  ['Frontend', 'public/js', /\.js$/],
];

function summary(file) {
  const text = fs.readFileSync(file, 'utf8').split('\n').slice(0, 40);
  const lines = [];
  let inBlock = false;
  for (const raw of text) {
    const line = raw.trim();
    if (!inBlock && line.startsWith('/**')) { inBlock = true; continue; }
    if (inBlock) {
      if (line.startsWith('*/')) break;
      lines.push(line.replace(/^\*\s?/, ''));
      continue;
    }
    if (line.startsWith('#!') || line === '' || /^[#/*\s=-]{6,}$/.test(line) || line.startsWith("'use strict'")) continue;
    if (line.startsWith('//') || (line.startsWith('#') && !line.startsWith('#!'))) {
      lines.push(line.replace(/^(\/\/|#)\s?/, ''));
      continue;
    }
    break;
  }
  const paragraphs = lines.join('\n').split(/\n\s*\n/).map((p) => p.replace(/\s+/g, ' ').trim()).filter(Boolean);
  // Skip a bare title line such as "Citadel Fleet Service" when a description follows it.
  let first = paragraphs[0] || '';
  if (first.length < 45 && paragraphs[1]) first = `${first.replace(/[.:]$/, '')}. ${paragraphs[1]}`;
  const sentence = first.match(/^(.+?[.!?])(\s|$)/);
  const out = (sentence ? sentence[1] : first).replace(/\.+$/, '').replace(/\|/g, '\\|');
  return out.length > 220 ? `${out.slice(0, 217)}...` : out || '_No header comment: add one._';
}

function screens() {
  const src = fs.readFileSync(path.join(ROOT, 'public/js/app.js'), 'utf8').split('\n');
  const rows = [];
  src.forEach((l, i) => {
    const m = l.match(/^ {2}(?:async )?function (render\w*View)\(/);
    if (m) rows.push(`| \`${m[1]}\` | \`public/js/app.js:${i + 1}\` |`);
  });
  return rows;
}

let md = '# Code map\n\nWhere things live. Generated by `scripts/code-map.js` from each file\'s header comment: do not edit by hand. For features, flags and behaviour see the [README](../README.md) and the other guides; for how to change things see [AGENTS.md](../AGENTS.md).\n';
const seen = new Set();
for (const [title, dir, re] of GROUPS) {
  const abs = path.join(ROOT, dir);
  const files = fs.readdirSync(abs).filter((f) => re.test(f) && fs.statSync(path.join(abs, f)).isFile()).sort();
  if (!files.length) continue;
  if (!seen.has(title)) { md += `\n## ${title}\n\n| File | Purpose |\n| --- | --- |\n`; seen.add(title); }
  for (const f of files) md += `| \`${dir}/${f}\` | ${summary(path.join(abs, f))} |\n`;
}
md += '\n## Tests\n\nOne suite per area in `tests/<area>.test.js` (`node:test`, each with its own throwaway database under `data/`). Match the name of the route, service or script you changed: `monitor.test.js` for `monitorService.js`, `pairing.test.js` for `pairingService.js`, and so on.\n';
md += '\n## Screens in `public/js/app.js`\n\nThe shell is one large file; jump to a screen by function name (`grep -n "function renderXView" public/js/app.js`). Line numbers are as of the last regeneration.\n\n| Screen function | Location |\n| --- | --- |\n';
md += `${screens().join('\n')}\n`;
fs.writeFileSync(path.join(ROOT, 'docs/code-map.md'), md);
console.log('docs/code-map.md updated.');
